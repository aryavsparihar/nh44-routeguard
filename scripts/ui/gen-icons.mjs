// Turns the Round 2 icons (docs/ux/assets/icons/*.svg) into src/ui/icons.tsx,
// so the app draws them as inline React SVG that takes the text colour
// (stroke="currentColor") without dangerouslySetInnerHTML.
//
//   node scripts/ui/gen-icons.mjs
//
// The icons use only <path>, <circle> and <rect>; anything else stops the script.
import fs from 'node:fs';
import path from 'node:path';

const DIR = 'docs/ux/assets/icons';
const OUT = 'src/ui/icons.tsx';
const ALLOWED = new Set(['path', 'circle', 'rect']);
const ATTRS = new Set(['d', 'cx', 'cy', 'r', 'x', 'y', 'width', 'height', 'rx', 'ry']);

const icons = {};
for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = fs.readFileSync(path.join(DIR, file), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<title[^>]*>[\s\S]*?<\/title>/, '');
  const shapes = [];
  for (const m of inner.matchAll(/<([a-z]+)([^>]*?)\/>/g)) {
    const [, tag, attrText] = m;
    if (!ALLOWED.has(tag)) throw new Error(`${file}: <${tag}> is not supported`);
    const attrs = {};
    for (const a of attrText.matchAll(/([a-z-]+)="([^"]*)"/g)) {
      if (!ATTRS.has(a[1])) throw new Error(`${file}: attribute ${a[1]} is not supported`);
      attrs[a[1]] = a[2];
    }
    shapes.push([tag, attrs]);
  }
  if (inner.replace(/<([a-z]+)([^>]*?)\/>/g, '').trim()) throw new Error(`${file}: unexpected content`);
  icons[file.replace(/\.svg$/, '')] = shapes;
}

const body = Object.entries(icons)
  .map(([name, shapes]) => {
    const els = shapes
      .map(([tag, attrs], i) => `<${tag} key={${i}} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')} />`)
      .join('\n      ');
    return `  "${name}": (\n    <>\n      ${els}\n    </>\n  ),`;
  })
  .join('\n');

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/ui/gen-icons.mjs from docs/ux/assets/icons/*.svg. Do not edit by hand.
import type { ReactNode } from "react";

const SHAPES = {
${body}
} satisfies Record<string, ReactNode>;

export type IconName = keyof typeof SHAPES;

// Decorative by default (aria-hidden). Pass a label when the icon is the only
// thing that says what something is.
export function Icon({ name, label, className = "size-6" }: { name: IconName; label?: string; className?: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      focusable="false"
    >
      {SHAPES[name]}
    </svg>
  );
}
`,
);
console.log(`wrote ${OUT} (${Object.keys(icons).length} icons)`);
