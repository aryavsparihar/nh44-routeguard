// Writes src/server/db/schema.ts (the Drizzle schema) from the real database.
//
//   npm run db:schema
//
// The SQL migrations in supabase/migrations stay the only way the database
// changes; this file only describes the result to Drizzle, the same way
// `npm run db:types` describes it to TypeScript. Run both after every
// migration. src/server/db/schema.typecheck.ts fails `npm run typecheck` if the
// two disagree about a table's columns.
//
// It runs scripts/db/introspect.sql with a read-only connection
// (supabase db query --read-only). Pass a saved JSON file instead to skip
// the database: node scripts/db/gen-drizzle-schema.mjs schema.json
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';

const OUT = 'src/server/db/schema.ts';

function introspect() {
  const json = process.argv[2]
    ? fs.readFileSync(process.argv[2], 'utf8')
    : execFileSync(
        'npx',
        ['--no-install', 'supabase', 'db', 'query', '--remote', '--read-only', '-f', 'scripts/db/introspect.sql',
          '--output-format', 'json'],
        { encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
      );
  return JSON.parse(json.slice(json.indexOf('{'))).rows[0].schema;
}

const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
// Static SQL from the database's own catalog, written into a sql`` template.
const sqlText = (s) => s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

function builder(col, enums) {
  switch (col.udt) {
    case 'text': return ['text()', 'text'];
    case 'int2': return ['smallint()', 'smallint'];
    case 'int4': return ['integer()', 'integer'];
    case 'int8': return ['bigint({ mode: "number" })', 'bigint'];
    case 'float8': return ['doublePrecision()', 'doublePrecision'];
    case 'numeric': {
      const p = col.precision != null ? `precision: ${col.precision}, ` : '';
      const s = col.scale != null ? `scale: ${col.scale}, ` : '';
      return [`numeric({ ${p}${s}mode: "number" })`, 'numeric'];
    }
    case 'bool': return ['boolean()', 'boolean'];
    case 'date': return ['date({ mode: "string" })', 'date'];
    case 'timestamptz': return ['timestamp({ withTimezone: true, mode: "date" })', 'timestamp'];
    case 'uuid': return ['uuid()', 'uuid'];
    case 'jsonb': return ['jsonb()', 'jsonb'];
    case 'geography': return ['geography()', null];
    default:
      if (enums.has(col.udt)) return [`${camel(col.udt)}()`, null];
      throw new Error(`No Drizzle mapping for ${col.table}.${col.column} (${col.type} / ${col.udt})`);
  }
}

function generate(s) {
  const enums = new Map((s.enums ?? []).map((e) => [e.name, e.values]));
  const identity = new Map((s.identity ?? []).map((i) => [`${i.table}.${i.column}`, i.kind]));
  const pks = new Map();
  for (const p of (s.pks ?? []).sort((a, b) => a.pos - b.pos)) {
    pks.set(p.table, [...(pks.get(p.table) ?? []), p.column]);
  }
  const relations = new Map();
  for (const c of s.columns) {
    const r = relations.get(c.table) ?? { kind: c.kind, columns: [] };
    r.columns.push(c);
    relations.set(c.table, r);
  }

  const imports = new Set(['pgEnum', 'pgTable', 'pgView', 'customType', 'primaryKey']);
  const body = [];
  for (const [name, values] of enums) {
    body.push(`export const ${camel(name)} = pgEnum("${name}", [${values.map((v) => JSON.stringify(v)).join(", ")}]);`);
  }
  body.push('');

  for (const [table, rel] of [...relations].sort(([a], [b]) => a.localeCompare(b))) {
    const isView = rel.kind === 'VIEW';
    const pk = pks.get(table) ?? [];
    const lines = rel.columns.map((c) => {
      const [code, imp] = builder(c, enums);
      if (imp) imports.add(imp);
      let out = code;
      if (!isView) {
        const id = identity.get(`${table}.${c.column}`);
        if (pk.length === 1 && pk[0] === c.column) out += '.primaryKey()';
        if (id === 'a') out += '.generatedAlwaysAsIdentity()';
        else if (id === 'd') out += '.generatedByDefaultAsIdentity()';
        else if (c.generated) out += `.generatedAlwaysAs(sql\`${sqlText(c.generated)}\`)`;
        else if (c.default != null) out += `.default(sql\`${sqlText(c.default)}\`)`;
        if (!c.nullable && pk.length !== 1) out += '.notNull()';
        else if (!c.nullable && pk[0] !== c.column) out += '.notNull()';
      }
      return `  ${c.column}: ${out},`;
    });
    if (isView) {
      body.push(`export const ${camel(table)} = pgView("${table}", {\n${lines.join('\n')}\n}).existing();`);
    } else {
      const extra = pk.length > 1
        ? `, (t) => [primaryKey({ columns: [${pk.map((c) => `t.${c}`).join(', ')}] })]`
        : '';
      body.push(`export const ${camel(table)} = pgTable("${table}", {\n${lines.join('\n')}\n}${extra}).enableRLS();`);
    }
    body.push('');
  }

  return `// GENERATED by scripts/db/gen-drizzle-schema.mjs from the live database
// (npm run db:schema). Do not edit by hand: change the database with a
// migration in supabase/migrations, then run npm run db:schema and npm run db:types.
//
// Property names are the column names (snake_case), so query results keep the
// shape the API already returns. timestamptz columns come back as Date
// objects; JSON responses turn them into ISO strings.
import { sql } from "drizzle-orm";
import {
  ${[...imports].sort().join(',\n  ')},
} from "drizzle-orm/pg-core";

// PostGIS points (extensions.geography(Point, 4326)), passed through as text.
// Build them in SQL with extensions.st_makepoint() rather than in JS.
const geography = customType<{ data: string; driverData: string }>({
  dataType: () => "extensions.geography(Point,4326)",
});

${body.join('\n').trimEnd()}
`;
}

// A type-level check that each Drizzle table or view has exactly the columns
// lib/database.types.ts (npm run db:types) lists. If one of the two files is
// regenerated after a migration and the other isn't, npm run typecheck fails.
function generateCheck(s) {
  const relations = new Map(s.columns.map((c) => [c.table, c.kind]));
  const lines = [...relations].sort(([a], [b]) => a.localeCompare(b)).map(([table, kind]) => {
    const ours = kind === 'VIEW' ? `typeof s.${camel(table)}._.selectedFields` : `typeof s.${camel(table)}.$inferSelect`;
    const theirs = kind === 'VIEW' ? `Pub["Views"]["${table}"]["Row"]` : `Pub["Tables"]["${table}"]["Row"]`;
    return `export type ${camel(table)}Columns = Check<SameKeys<${ours}, ${theirs}>>;`;
  });
  return `// GENERATED by scripts/db/gen-drizzle-schema.mjs. Do not edit by hand.
// Fails npm run typecheck when src/server/db/schema.ts and
// lib/database.types.ts disagree about a table's columns: run npm run
// db:schema and npm run db:types after every migration.
import type { Database } from "@/lib/database.types";
import type * as s from "./schema";

type Pub = Database["public"];
type SameKeys<A, B> = [keyof A] extends [keyof B] ? ([keyof B] extends [keyof A] ? true : false) : false;
type Check<T extends true> = T;

${lines.join('\n')}
`;
}

const described = introspect();
fs.mkdirSync('src/server/db', { recursive: true });
fs.writeFileSync(OUT, generate(described));
fs.writeFileSync('src/server/db/schema.typecheck.ts', generateCheck(described));
console.log(`wrote ${OUT} and src/server/db/schema.typecheck.ts`);
